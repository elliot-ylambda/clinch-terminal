use std::error::Error;
use std::fs;
use std::path::PathBuf;

use clinch_companion_protocol::{
    AUTH_CHALLENGE_TTL_SECS, AUTH_SESSION_TTL_SECS, BINARY_FRAME_HEADER_BYTES, BINARY_FRAME_MAGIC,
    CompanionProtocolSchema, MAX_IDEMPOTENCY_RESULTS_PER_SESSION, MAX_JAVASCRIPT_SAFE_INTEGER,
    MAX_JSON_MESSAGE_BYTES, MAX_TERMINAL_FRAME_BYTES, MAX_UPLOAD_BYTES, MAX_UPLOAD_CHUNK_BYTES,
    PAIRING_INVITATION_TTL_SECS, PROTOCOL_VERSION, WRITER_LEASE_TTL_SECS,
};
use schemars::schema_for;
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn Error>> {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let workspace_dir = manifest_dir
        .parent()
        .and_then(|crates| crates.parent())
        .ok_or("protocol crate must live under <workspace>/crates")?;
    let mut arguments = std::env::args().skip(1);
    let generated_dir = match arguments.next().as_deref() {
        None => workspace_dir.join("web/remote-control/src/generated"),
        Some("--out-dir") => PathBuf::from(arguments.next().ok_or("--out-dir needs a path")?),
        Some(argument) => return Err(format!("unknown argument: {argument}").into()),
    };
    if arguments.next().is_some() {
        return Err("too many arguments".into());
    }
    let type_dir = generated_dir.join("types");
    if type_dir.exists() {
        fs::remove_dir_all(&type_dir)?;
    }
    fs::create_dir_all(&type_dir)?;

    let config = Config::new()
        .with_out_dir(&type_dir)
        .with_large_int("number");
    CompanionProtocolSchema::export_all(&config)?;
    for entry in fs::read_dir(&type_dir)? {
        let path = entry?.path();
        if path.extension().and_then(|extension| extension.to_str()) != Some("ts") {
            continue;
        }

        let generated = fs::read_to_string(&path)?;
        let normalized = generated
            .lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n");
        fs::write(path, format!("{normalized}\n"))?;
    }

    let schema = schema_for!(CompanionProtocolSchema);
    fs::write(
        generated_dir.join("protocol.schema.json"),
        format!("{}\n", serde_json::to_string_pretty(&schema)?),
    )?;

    fs::write(
        generated_dir.join("constants.ts"),
        format!(
            "// Generated by `cargo run -p clinch_companion_protocol --bin generate`.\n\
             // Do not edit by hand.\n\n\
             export const PROTOCOL_VERSION = {PROTOCOL_VERSION} as const;\n\
             export const PAIRING_INVITATION_TTL_SECS = {PAIRING_INVITATION_TTL_SECS} as const;\n\
             export const AUTH_CHALLENGE_TTL_SECS = {AUTH_CHALLENGE_TTL_SECS} as const;\n\
             export const AUTH_SESSION_TTL_SECS = {AUTH_SESSION_TTL_SECS} as const;\n\
             export const WRITER_LEASE_TTL_SECS = {WRITER_LEASE_TTL_SECS} as const;\n\
             export const MAX_JAVASCRIPT_SAFE_INTEGER = {MAX_JAVASCRIPT_SAFE_INTEGER} as const;\n\
             export const MAX_JSON_MESSAGE_BYTES = {MAX_JSON_MESSAGE_BYTES} as const;\n\
             export const MAX_UPLOAD_BYTES = {MAX_UPLOAD_BYTES} as const;\n\
             export const MAX_UPLOAD_CHUNK_BYTES = {MAX_UPLOAD_CHUNK_BYTES} as const;\n\
             export const MAX_TERMINAL_FRAME_BYTES = {MAX_TERMINAL_FRAME_BYTES} as const;\n\
             export const MAX_IDEMPOTENCY_RESULTS_PER_SESSION = {MAX_IDEMPOTENCY_RESULTS_PER_SESSION} as const;\n\
             export const BINARY_FRAME_MAGIC = [{}, {}] as const;\n\
             export const BINARY_FRAME_HEADER_BYTES = {BINARY_FRAME_HEADER_BYTES} as const;\n",
            BINARY_FRAME_MAGIC[0], BINARY_FRAME_MAGIC[1]
        ),
    )?;

    Ok(())
}
